-- Flyway migration: create table to store textual session drafts per user
CREATE TABLE IF NOT EXISTS sessao_draft (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_sessao DATE NOT NULL,
  anotacoes TEXT,
  usuario_id BIGINT NOT NULL,
  CONSTRAINT fk_sessao_draft_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_sessao_draft_usuario_data ON sessao_draft(usuario_id, data_sessao);
